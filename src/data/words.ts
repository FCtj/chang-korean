function makeRound(id: string, tier: number, no: number, title: L10n, rows: Row[]): Round {
  return {
    id,
    tier,
    no,
    title,
    words: rows.map(([ko, rom, lo, th, emoji], i) => ({
      id: `${id}-${String(i + 1).padStart(2, '0')}`,
      ko,
      rom,
      lo,
      th,
      emoji,
      roundId: id,
    })),
  }
}

