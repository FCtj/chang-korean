export const SET_SIZE = 5 // 5개씩 묶어서 반복
export const PROMO_QUESTIONS = 30

export function roundSets(round: Round): Word[][] {
  const sets: Word[][] = []
  for (let i = 0; i < round.words.length; i += SET_SIZE) sets.push(round.words.slice(i, i + SET_SIZE))
  return sets
}

